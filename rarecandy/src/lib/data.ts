export const cards: Card[] = drafts.map((draft) => {
  const { popScale, ...rest } = draft;
  return {
    ...rest,
    priceHistory: history(draft.marketPrice, draft.id),
    recentSales: sales(draft.marketPrice, draft.id),
    listings: listingsFor(draft.id, draft.marketPrice, S),
    populations: pops(draft.id, popScale),
  };
});

export function getCard(slug: string) {
  return cards.find((card) => card.slug === slug);
}

export function getSet(slug: string) {
  return sets.find((set) => set.slug === slug);
}

export function getSetById(id: string) {
  return sets.find((set) => set.id === id);
}

export function getSeller(id: string) {
  return sellers.find((seller) => seller.id === id);
}

export function getListing(listingId: string) {
  for (const card of cards) {
    const listing = card.listings.find((item) => item.id === listingId);
    if (listing) return { listing, card };
  }
  return undefined;
}

export function cardsInSet(setId: string) {
  return cards.filter((card) => card.setId === setId);
}

export function relatedCards(card: Card, limit = 4) {
  return cards
    .filter((other) => other.id !== card.id)
    .map((other) => {
      let score = 0;
      if (other.pokemon === card.pokemon) score += 6;
      if (other.setId === card.setId) score += 3;
      if (other.type === card.type) score += 1;
      if (other.rarity === card.rarity) score += 1;
      return { other, score };
    })
    .sort((a, b) => b.score - a.score || b.other.marketPrice - a.other.marketPrice)
    .slice(0, limit)
    .map((entry) => entry.other);
}

export function featuredCards() {
  return cards.filter((card) => card.featured);
}

export function trendingCards() {
  return [...cards]
    .filter((card) => card.trending)
    .sort((a, b) => Math.abs(b.change7d) - Math.abs(a.change7d));
}

export function newCards() {
  return cards.filter((card) => card.isNew);
}

export function recentMarketSales() {
  return cards
    .flatMap((card) =>
      card.recentSales.slice(0, 2).map((sale) => ({ card, sale })),
    )
    .sort((a, b) => b.sale.date.localeCompare(a.sale.date))
    .slice(0, 18);
}

