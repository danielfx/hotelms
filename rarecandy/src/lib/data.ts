function seedHash(seed: string) {
  let h = 2166136261;
  for (let i = 0; i < seed.length; i++) {
    h ^= seed.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

function rand(seed: number) {
  const x = Math.sin(seed) * 10000;
  return x - Math.floor(x);
}

function history(base: number, seed: string, weeks = 52): PricePoint[] {
  const s = seedHash(seed);
  const points: PricePoint[] = [];
  let price = base * (0.62 + rand(s) * 0.12);
  for (let i = weeks; i >= 0; i--) {
    const t = (weeks - i) / weeks;
    const wave = Math.sin(s / 1000 + i / 7) * 0.055;
    const noise = (rand(s + i * 17) - 0.5) * 0.045;
    const drift = t * 0.28;
    price = base * (0.7 + drift + wave + noise);
    const d = new Date("2026-08-17T00:00:00Z");
    d.setDate(d.getDate() - i * 7);
    points.push({
      date: d.toISOString().slice(0, 10),
      price: Math.max(8, Math.round(price)),
    });
  }
  points[points.length - 1].price = base;
  return points;
}

function sales(
  base: number,
  seed: string,
  count = 8,
): Sale[] {
  const s = seedHash(seed);
  const sources = ["PWCC", "Goldin", "eBay", "Heritage", "Private", "RareCandy"];
  const grades = [
    { condition: "Near Mint", grade: undefined, company: undefined, mult: 1 },
    { condition: "Mint", grade: "10", company: "PSA" as GradingCompany, mult: 2.4 },
    { condition: "Mint", grade: "9", company: "PSA" as GradingCompany, mult: 1.35 },
    { condition: "Mint", grade: "9.5", company: "BGS" as GradingCompany, mult: 1.7 },
    { condition: "Mint", grade: "10", company: "CGC" as GradingCompany, mult: 1.9 },
    { condition: "Lightly Played", grade: undefined, company: undefined, mult: 0.72 },
    { condition: "Mint", grade: "8", company: "PSA" as GradingCompany, mult: 0.95 },
    { condition: "Near Mint", grade: "9.5", company: "CGC" as GradingCompany, mult: 1.45 },
  ];
  return Array.from({ length: count }, (_, i) => {
    const g = grades[(s + i * 3) % grades.length];
    const d = new Date("2026-08-16T00:00:00Z");
    d.setDate(d.getDate() - (i * 6 + ((s + i) % 5)));
    const jitter = 0.92 + rand(s + i * 31) * 0.16;
    return {
      id: `${seed}-sale-${i}`,
      date: d.toISOString().slice(0, 10),
      price: Math.max(12, Math.round(base * g.mult * jitter)),
      condition: g.condition,
      grade: g.grade,
      company: g.company,
      source: sources[(s + i) % sources.length],
    };
  });
}

function pops(seed: string, scale: number): GradePop[] {
  const s = seedHash(seed);
  const psa10 = Math.max(4, Math.round(scale * (0.04 + rand(s) * 0.08)));
  const psa9 = Math.max(18, Math.round(scale * (0.22 + rand(s + 1) * 0.12)));
  const psa8 = Math.max(30, Math.round(scale * (0.28 + rand(s + 2) * 0.1)));
  const bgs95 = Math.max(6, Math.round(scale * (0.05 + rand(s + 3) * 0.05)));
  const bgs10 = Math.max(1, Math.round(scale * (0.008 + rand(s + 4) * 0.012)));
  const cgc10 = Math.max(3, Math.round(scale * (0.03 + rand(s + 5) * 0.04)));
  const cgc95 = Math.max(10, Math.round(scale * (0.08 + rand(s + 6) * 0.06)));
  return [
    { company: "PSA", grade: "10", population: psa10 },
    { company: "PSA", grade: "9", population: psa9 },
    { company: "PSA", grade: "8", population: psa8 },
    { company: "BGS", grade: "10", population: bgs10 },
    { company: "BGS", grade: "9.5", population: bgs95 },
    { company: "CGC", grade: "10", population: cgc10 },
    { company: "CGC", grade: "9.5", population: cgc95 },
  ];
}

